/*
# Create bulk orders table

1. New Table
- `bulk_orders`: one row per bulk order request submitted from the website.
  - `reference`: unique order reference generated by the website (for example DPC-BLK-7KQ2-X8MZ3P).
  - `status`: Pending, Quoted, Accepted, Processing, Ready for Delivery, Delivered or Cancelled. New requests start as Pending.
  - Customer details: customer or organization name, contact person, WhatsApp number, optional organization, service type.
  - `items`: JSON list of requested items with name, quantity, optional printing specifications and optional unit price.
  - `delivery_location`: JSON describing the on-campus hostel, off-campus accommodation or other location.
  - Delivery date and time, optional budget, optional instructions.
  - `internal_notes` and `customer_response`: written only by administrators.

2. Security
- RLS enabled.
- Anyone on the website (anon and signed-in) can insert a new request, but only as Pending and with no admin fields filled in.
- Anyone can insert, but nobody can read rows through the public key, so customers cannot see each other's requests.
- Signed-in administrators (listed in `admin_users`) can read all requests and update only `status`, `internal_notes`, `customer_response` and `updated_at`.
- No delete permission is granted to anyone through the API.

3. Notes
- Public inserts are open by design because the website has no sign-in for customers yet. Basic limits on text length, item count and WhatsApp format are enforced in the database.
*/

CREATE TABLE IF NOT EXISTS bulk_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE CHECK (reference ~ '^DPC-BLK-[A-Z0-9]{4}-[A-Z0-9]{6}$'),
  status text NOT NULL DEFAULT 'Pending' CHECK (
    status IN ('Pending', 'Quoted', 'Accepted', 'Processing', 'Ready for Delivery', 'Delivered', 'Cancelled')
  ),
  customer_name text NOT NULL CHECK (char_length(btrim(customer_name)) BETWEEN 2 AND 120),
  contact_name text NOT NULL CHECK (char_length(btrim(contact_name)) BETWEEN 2 AND 120),
  whatsapp text NOT NULL CHECK (whatsapp ~ '^0[789][01][0-9]{8}$'),
  organization text CHECK (organization IS NULL OR char_length(organization) <= 160),
  service_type text NOT NULL CHECK (char_length(service_type) BETWEEN 2 AND 80),
  items jsonb NOT NULL CHECK (
    jsonb_typeof(items) = 'array' AND jsonb_array_length(items) BETWEEN 1 AND 100
  ),
  delivery_location jsonb NOT NULL CHECK (jsonb_typeof(delivery_location) = 'object'),
  delivery_date date NOT NULL,
  delivery_time text NOT NULL CHECK (char_length(delivery_time) BETWEEN 2 AND 80),
  budget text CHECK (budget IS NULL OR char_length(budget) <= 80),
  instructions text CHECK (instructions IS NULL OR char_length(instructions) <= 2000),
  internal_notes text CHECK (internal_notes IS NULL OR char_length(internal_notes) <= 4000),
  customer_response text CHECK (customer_response IS NULL OR char_length(customer_response) <= 4000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
